const BUILD_SCHEMA = {
  type: 'object',
  properties: {
    phase: { type: 'string' },
    filesTouched: { type: 'array', items: { type: 'string' } },
    testsAddedOrChanged: { type: 'array', items: { type: 'string' } },
    commandsRun: { type: 'array', items: { type: 'object', properties: { cmd: { type: 'string' }, outcome: { type: 'string' } }, required: ['cmd', 'outcome'] } },
    honestGaps: { type: 'array', items: { type: 'string' }, description: 'What is NOT done, needs a human, or was out of scope - stated plainly.' },
    handoffs: { type: 'array', items: { type: 'string' }, description: 'Files you needed but do not own.' },
    summary: { type: 'string' },
  },
  required: ['phase', 'filesTouched', 'testsAddedOrChanged', 'commandsRun', 'honestGaps', 'handoffs', 'summary'],
}

const REVIEW_SCHEMA = {
  type: 'object',
  properties: {
    phase: { type: 'string' },
    lens: { type: 'string' },
    findings: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          severity: { type: 'string', description: 'blocker | should-fix | improvement | note' },
          file: { type: 'string' },
          issue: { type: 'string' },
          fix: { type: 'string', description: 'Concrete enough that the fixer can act without re-deriving it.' },
        },
        required: ['severity', 'file', 'issue', 'fix'],
      },
    },
    verdict: { type: 'string' },
  },
  required: ['phase', 'lens', 'findings', 'verdict'],
}

const FIX_SCHEMA = {
  type: 'object',
  properties: {
    phase: { type: 'string' },
    applied: { type: 'array', items: { type: 'string' } },
    skipped: { type: 'array', items: { type: 'object', properties: { finding: { type: 'string' }, why: { type: 'string' } }, required: ['finding', 'why'] } },
    filesTouched: { type: 'array', items: { type: 'string' } },
    summary: { type: 'string' },
  },
  required: ['phase', 'applied', 'skipped', 'filesTouched', 'summary'],
}

const VERIFY_SCHEMA = {
  type: 'object',
  properties: {
    phase: { type: 'string' },
    checks: { type: 'array', items: { type: 'object', properties: { name: { type: 'string' }, pass: { type: 'boolean' }, evidence: { type: 'string' } }, required: ['name', 'pass', 'evidence'] } },
    claimsRechecked: { type: 'number' },
    overturned: { type: 'array', items: { type: 'string' } },
    ready: { type: 'boolean', description: 'true only if every blocker is closed and every claim survived.' },
    summary: { type: 'string' },
  },
  required: ['phase', 'checks', 'claimsRechecked', 'overturned', 'ready', 'summary'],
}

const ownsBlock = (p) => ['YOUR PHASE OWNS EXACTLY THESE PATHS - nothing else:', ...p.owns.map((o) => '  - ' + o)].join('\n')

const buildPrompt = (p) => [RULES, '', ownsBlock(p), '', 'PHASE ' + p.key + ': ' + p.title, '', p.spec, '', 'Build it. Your report is data for reviewers, not a human-facing message - fill honestGaps truthfully; a gap you name costs nothing, a gap a reviewer finds costs the phase.'].join('\n')

const reviewPrompt = (p, lens, build) => {
  const lenses = {
    scope: [
'LENS: SCOPE. Answer one question ruthlessly: did this phase build WHAT IT WAS',
'TOLD TO, all of it, and NOTHING else? Diff the owned paths (git diff --',
'<paths>), walk the spec line by line, and flag: spec items silently dropped,',
'work outside the owned paths, scope creep dressed as improvement, and',
'anything the spec forbade that happened anyway. An honest honestGaps entry is',
'fine; an unlisted gap is a blocker.',
    ],
    quality: [
'LENS: QUALITY. Is the work good by THIS repo standard? Tests: real assertions',
'or theatre? Written RED-first where there is logic (the report commandsRun',
'should show a failing run before a passing one - absence is a should-fix)?',
'Comments: WHY-heavy in the repo voice, and TRUE - a comment that overclaims is',
'a defect here (this repo has been burned by exactly that; see the speakSafely',
'story in aa278cd). Naming, dead code, duplication, British spelling, Rs not',
'the rupee word. Config changes verified mechanically rather than by eye?',
    ],
    critic: [
'LENS: ADVERSARIAL CRITIC. Your job is to find what is WRONG and what would',
'make this BETTER, and you succeed by breaking things, not by approving them.',
'Attack: edge cases the tests miss, the failure mode nobody wrote down, the',
'assumption that is false on a cheap Android phone or a flaky Indian network,',
'the thing that breaks when the OTHER three phases land beside this one (read',
'their specs in docs/prd/_wave1.js), the contrast pair or CHECK constraint or',
'YAML branch nobody exercised. Then: the two or three cheap changes that would',
'make this genuinely better, concrete enough to apply today. Reproduce at',
'least one finding with a real command where possible - a demonstrated break',
'outranks ten suspicions.',
    ],
  }
  return [RULES, '', ownsBlock(p), '', 'PHASE ' + p.key + ': ' + p.title, '', 'THE SPEC THE BUILDER WAS GIVEN:', p.spec, '', 'THE BUILDER REPORT:', JSON.stringify(build, null, 2), '', lenses[lens].join('\n'), '', 'You edit NOTHING. Findings must be concrete: file, issue, fix. Severity honestly - blocker means ship-stopping, not pet peeve.'].join('\n')
}

const fixPrompt = (p, build, reviews) => [RULES, '', ownsBlock(p), '', 'PHASE ' + p.key + ': ' + p.title, '', 'Three reviewers (scope, quality, adversarial critic) examined the build.',
'Apply their findings: every blocker and should-fix, and any improvement that',
'is cheap and inside the owned paths. Skip - with a written why - anything',
'that expands scope, contradicts the spec, or is wrong (reviewers are also',
'fallible; check a finding against the tree before acting on it). Re-run the',
'targeted tests after. TDD applies to your fixes too where they change logic.',
'', 'THE SPEC:', p.spec, '', 'BUILDER REPORT:', JSON.stringify(build, null, 2), '', 'FINDINGS:', JSON.stringify(reviews, null, 2)].join('\n')

const verifyPrompt = (p, fix) => [RULES, '', ownsBlock(p), '', 'PHASE ' + p.key + ': ' + p.title, '', 'You are the last gate before stitch. Verify by DOING, not by reading reports:',
'run the phase targeted tests yourself, run the phase verification commands',
'yourself (build-theme check for A, YAML parse for B, migrations test for C,',
'the WER unit test and corpus writer for G), re-check every factual claim in',
'the reports below against the tree, and confirm not one file outside the',
'owned paths changed (git diff --name-only, then subtract the owned paths -',
'remember three sibling phases are editing THEIR files, so judge only whether',
'THIS phase stayed inside its own).',
'Do not run the full suite, the full typecheck or the build - stitch does.',
'ready=true only if every blocker closed and every claim survived.',
'', 'THE SPEC:', p.spec, '', 'FIX REPORT:', JSON.stringify(fix, null, 2)].join('\n')

log('Wave 1: four phases, disjoint files, each under build -> scope+quality+critic -> fix -> verify.')

phase('Build')

const results = await pipeline(
  PHASES,
  (p) => agent(buildPrompt(p), { label: 'build:' + p.key, phase: 'Build', schema: BUILD_SCHEMA, effort: 'high' }),
  (build, p) =>
    parallel([
      () => agent(reviewPrompt(p, 'scope', build), { label: 'scope:' + p.key, phase: 'Review', schema: REVIEW_SCHEMA }),
      () => agent(reviewPrompt(p, 'quality', build), { label: 'quality:' + p.key, phase: 'Review', schema: REVIEW_SCHEMA }),
      () => agent(reviewPrompt(p, 'critic', build), { label: 'critic:' + p.key, phase: 'Review', schema: REVIEW_SCHEMA, effort: 'high' }),
    ]).then((reviews) => ({ build, reviews: reviews.filter(Boolean) })),
  (acc, p) =>
    agent(fixPrompt(p, acc.build, acc.reviews), { label: 'fix:' + p.key, phase: 'Fix', schema: FIX_SCHEMA, effort: 'high' })
      .then((fix) => ({ ...acc, fix })),
  (acc, p) =>
    agent(verifyPrompt(p, acc.fix), { label: 'verify:' + p.key, phase: 'Verify', schema: VERIFY_SCHEMA, effort: 'high' })
      .then((verify) => ({ phase: p.key, title: p.title, ...acc, verify })),
)

const done = results.filter(Boolean)
log(done.length + '/4 phases through the full pipeline.')

return {
  phases: done.map((d) => ({
    phase: d.phase,
    title: d.title,
    ready: d.verify?.ready ?? false,
    builderGaps: d.build?.honestGaps ?? [],
    findingsBySeverity: (d.reviews ?? []).flatMap((r) => r.findings ?? []).reduce((m, f) => { m[f.severity] = (m[f.severity] ?? 0) + 1; return m }, {}),
    fixed: d.fix?.applied?.length ?? 0,
    skipped: d.fix?.skipped ?? [],
    overturned: d.verify?.overturned ?? [],
    verifySummary: d.verify?.summary ?? '',
  })),
  detail: done,
}
