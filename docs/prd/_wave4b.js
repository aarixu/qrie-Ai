const BUILD_SCHEMA = {
  type: 'object',
  properties: {
    phase: { type: 'string' },
    filesTouched: { type: 'array', items: { type: 'string' } },
    testsAddedOrChanged: { type: 'array', items: { type: 'string' } },
    commandsRun: { type: 'array', items: { type: 'object', properties: { cmd: { type: 'string' }, outcome: { type: 'string' } }, required: ['cmd', 'outcome'] } },
    contracts: { type: 'array', items: { type: 'string' }, description: 'Shapes another phase or wave consumes, spelled exactly.' },
    costEffect: { type: 'string', description: 'What this changes in Rs/student-hour, with arithmetic, or "none" and why.' },
    honestGaps: { type: 'array', items: { type: 'string' } },
    handoffs: { type: 'array', items: { type: 'string' } },
    summary: { type: 'string' },
  },
  required: ['phase', 'filesTouched', 'testsAddedOrChanged', 'commandsRun', 'contracts', 'costEffect', 'honestGaps', 'handoffs', 'summary'],
}

const REVIEW_SCHEMA = {
  type: 'object',
  properties: {
    phase: { type: 'string' },
    lens: { type: 'string' },
    findings: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          severity: { type: 'string', description: 'blocker | should-fix | improvement | note' },
          file: { type: 'string' },
          issue: { type: 'string' },
          fix: { type: 'string' },
        },
        required: ['severity', 'file', 'issue', 'fix'],
      },
    },
    verdict: { type: 'string' },
  },
  required: ['phase', 'lens', 'findings', 'verdict'],
}

const FIX_SCHEMA = {
  type: 'object',
  properties: {
    phase: { type: 'string' },
    applied: { type: 'array', items: { type: 'string' } },
    skipped: { type: 'array', items: { type: 'object', properties: { finding: { type: 'string' }, why: { type: 'string' } }, required: ['finding', 'why'] } },
    filesTouched: { type: 'array', items: { type: 'string' } },
    summary: { type: 'string' },
  },
  required: ['phase', 'applied', 'skipped', 'filesTouched', 'summary'],
}

