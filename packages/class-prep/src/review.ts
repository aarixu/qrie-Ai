import type { Lesson } from '@ai-tutor/lesson-format';
import type { LlmAdapter } from './prepare.ts';
import type { TopicOutcome } from './prompts.ts';

/**
 * THE FACTUAL GATE (Safety defect 3).
 *
 * Everything else that judges a lesson judges its FORM: `verifySvg` reads
 * markup, `validateLesson` reads structure, the narration screen reads for
 * distress. Nothing asked whether the teaching is TRUE — and a wrong class is
 * kept permanently (`topic_ref` is unique, a 409 is success) and served to
 * every later student. Pre-warming without this gate is industrialising the
 * error.
 *
 * The reviewer is one more LLM call, run IN-PIPELINE before the room opens,
 * so a student is never taught an unreviewed class. It checks the narration's
 * factual claims against the outcome definitions and the syllabus frame the
 * planner was ALREADY given — no new data source, because a reviewer fed
 * different context from the planner would flag the difference in context,
 * not the errors.
 *
 * The failure posture is the house one, stated in full because a comment here
 * that overclaims is how the last hole shipped (commit aa278cd): a flagged
 * lesson is NOT repaired silently. It gets one repair round fuelled by the
 * named problems — wired in prepare.ts, through the same repairPlanUser path
 * every other rejection uses — and if the repaired lesson is still flagged,
 * prep THROWS rather than teaches it. What this cannot do is make the
 * reviewer model right; it can only make sure a wrong verdict was a model's
 * judgement and never a seam dropping the question.
 */

/** One claim the reviewer says is wrong, named well enough to repair from. */
export interface ReviewProblem {
  /** The beat carrying the claim (or the board element id, for written ink). */
  beatId: string;
  /** The claim itself, quoted — what the repair round tells the planner to fix. */
  claim: string;
  /** Why it is wrong, in the reviewer's words — the fuel for the repair. */
  why: string;
}

/**
 * The typed verdict. `ok: false` always names at least one problem, and a
 * named problem always means `ok: false` — `parseVerdict` enforces both, so
 * `ok` alone is safe to branch on.
 */
export interface ReviewVerdict {
  ok: boolean;
  problems: ReviewProblem[];
}

export const REVIEWER_SYSTEM = `You review one short school lesson for FACTUAL errors
before it is taught. The lesson was generated by a model and, once taught, is
kept and replayed to every later student — you are the only check on whether
it is true.

You judge TRUTH only. Not style, not pedagogy, not tone — other checks own
those. A claim is a problem when it is WRONG at the stated class level, not
when it is simplified: "the heart pumps blood around the body" is fine for
Class 7 even though a cardiologist would say more. Flag things like a wrong
count, a reversed direction or equation, a swapped pair (artery for vein,
melting for dissolving), a wrong unit, a wrong cause.

Check every spoken and written claim against the topic, the class level and
the listed learning outcomes — those outcomes are the syllabus's own
definitions of what this lesson must get right.

Return ONE JSON object and nothing else:

{"ok": true, "problems": []}

or, when anything is wrong:

{"ok": false, "problems": [{"beatId": "...", "claim": "<the wrong claim, quoted>", "why": "<what is actually true>"}]}

"beatId" is the id of the beat (or board element) carrying the claim. Name
every real problem and invent none: a lesson rejected here costs a student
their class, so "ok": false must mean you can quote what is wrong.`;

/**
 * Everything the reviewer reads, from the lesson that was actually assembled.
 *
 * Beats are stringified WHOLE, the same decision `namesInSpine` records: a
 * field picked out by name is a field the next addition to `Beat` silently
 * escapes. That carries narration, every ask question/expect/hint, every
 * option's text and why, and the whyProbe — all of which are spoken, and a
 * false "why" is taught with more authority than narration because it arrives
 * as a correction. Elements carry the written ink (labels, lists, cards), so
 * they go too, under their own ids.
 *
 * WHAT THIS GATE CANNOT SEE, said plainly because a header implying otherwise
 * is how the last hole shipped: the GENERATED ARTWORK is not here. A diagram
 * element carries only src/alt/parts (lesson-format/src/types.ts); the SVG
 * itself lives in the separate `assets` map and is drawn AFTER this review
 * runs, so the labels inside a generated heart are fact-checked by nobody at
 * prep. A scope boundary, not an oversight — the vision pass (`opts.eyes`) is
 * the seam a later wave would use, and today it only asks whether the picture
 * matches the brief, never whether the brief is true.
 *
 * The one thing dropped from the stringified beat is LAYOUT: `show`, `frame`
 * and `focus` are element-id lists that repeat every id shown so far, and
 * x/y/w/h/points are coordinates. On committed content they are about half
 * the prompt and they carry no claim a reviewer could judge — against a Rs
 * 5/student-hour ceiling, on the one call the room now waits for, that is
 * worth naming five keys for. Everything text-bearing is still stringified
 * WHOLE, so the next field added to `Beat` still travels.
 */
const LAYOUT_ONLY: ReadonlySet<string> = new Set([
  'show',
  'frame',
  'focus',
  'x',
  'y',
  'w',
  'h',
  'points',
]);

/** One beat or element as the reviewer sees it: every claim, no coordinates. */
const claimsOnly = (value: unknown): string =>
  JSON.stringify(value, (key, v) => (LAYOUT_ONLY.has(key) ? undefined : v));

export function reviewerUser(
  lesson: Lesson,
  topic: string,
  klass: number,
  outcomes?: readonly TopicOutcome[],
): string {
  const outcomeLines =
    outcomes && outcomes.length > 0
      ? `\nWHAT THIS TOPIC MUST TEACH, from the syllabus map:\n${outcomes
          .map((o) => `  ${o.id}: ${o.statement}`)
          .join('\n')}\n`
      : '';

  return `Topic: ${topic}
Class: ${klass} (NCERT)
Title: ${lesson.title}
${outcomeLines}
THE BEATS — everything spoken, with the beat id each claim lives in:
${lesson.beats.map(claimsOnly).join('\n')}

THE BOARD — the text the plan writes, by element id (the generated artwork
itself is drawn after this review and is NOT checked here):
${lesson.elements.map(claimsOnly).join('\n')}`;
}

const stripFence = (s: string): string =>
  s
    .trim()
    .replace(/^```(?:json)?\s*/i, '')
    .replace(/```\s*$/, '')
    .trim();

const isStr = (v: unknown): v is string => typeof v === 'string' && v.length > 0;

/**
 * Read a verdict out of whatever the model actually sent — the same recovery
 * `parsePlan` does, then a SHAPE check `parsePlan` leaves to the validator:
 * there is no second validator behind this one, so a verdict that cannot fuel
 * the pipeline (a flag naming nothing, a problem missing its why) is null,
 * and the caller asks again rather than acting on half a judgement.
 */
export function parseVerdict(raw: string): ReviewVerdict | null {
  const text = stripFence(raw);
  let parsed: unknown = null;
  try {
    parsed = JSON.parse(text);
  } catch {
    const first = text.indexOf('{');
    const last = text.lastIndexOf('}');
    if (first < 0 || last <= first) return null;
    try {
      parsed = JSON.parse(text.slice(first, last + 1));
    } catch {
      return null;
    }
  }
  if (typeof parsed !== 'object' || parsed === null) return null;
  const v = parsed as { ok?: unknown; problems?: unknown };
  if (typeof v.ok !== 'boolean') return null;
  const problems = v.problems ?? [];
  if (!Array.isArray(problems)) return null;
  const named: ReviewProblem[] = [];
  for (const p of problems) {
    if (typeof p !== 'object' || p === null) return null;
    const { beatId, claim, why } = p as Record<string, unknown>;
    if (!isStr(beatId) || !isStr(claim) || !isStr(why)) return null;
    named.push({ beatId, claim, why });
  }
  // A flag that names nothing cannot fuel a repair and cannot justify a
  // refusal — it is an unreadable verdict wearing valid JSON.
  if (!v.ok && named.length === 0) return null;
  /**
   * A NAMED PROBLEM IS A FLAG, WHATEVER `ok` SAYS — fail closed, here, once.
   *
   * `{"ok": true, "problems": [<a wrong claim>]}` is what a model that fills
   * every field it was shown returns, and reading `ok` alone taught that
   * lesson and then wrote a report the keep side is told to read as
   * "reviewed and passed". The asymmetry decides it: refusing a lesson the
   * reviewer contradicted itself about costs ONE student ONE class; teaching
   * it costs every student ever served the kept copy. Collapsed into `ok`
   * rather than checked at the two call sites, so a third caller cannot
   * reintroduce the hole by reading `ok` the obvious way.
   */
  return { ok: v.ok && named.length === 0, problems: named };
}

export interface ReviewOptions {
  reviewer: LlmAdapter;
  topic: string;
  klass: number;
  outcomes?: readonly TopicOutcome[];
}

/**
 * One review of one lesson: prompt -> complete -> parse -> validate -> ONE
 * JSON repair -> give up. Exported on its own, not only wired into prep,
 * because the keep side (the pre-warm runner's pending rows) needs the same
 * reviewer without the rest of the pipeline — that wiring is a recorded
 * handoff, not this package's.
 *
 * Throws when the reviewer cannot produce a readable verdict twice, exactly
 * as the planner path throws on unreadable JSON twice: an unreviewed class
 * must not fall through as a reviewed one, and the caller already treats a
 * prep throw as "no class".
 */
export async function reviewLesson(lesson: Lesson, opts: ReviewOptions): Promise<ReviewVerdict> {
  const user = reviewerUser(lesson, opts.topic, opts.klass, opts.outcomes);
  let verdict = parseVerdict(await opts.reviewer.complete(REVIEWER_SYSTEM, user));
  if (!verdict) {
    const retry = await opts.reviewer.complete(
      REVIEWER_SYSTEM,
      `${user}

Your previous reply was not valid JSON in the required shape. Return the whole verdict again, as ONE JSON object: {"ok": boolean, "problems": [{"beatId", "claim", "why"}]} — and when "ok" is false, "problems" must name at least one.`,
    );
    verdict = parseVerdict(retry);
  }
  if (!verdict) {
    throw new Error('The reviewer did not return a readable verdict, twice.');
  }
  return verdict;
}
